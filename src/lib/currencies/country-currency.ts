/**
 * Returns the currency normally used for retail prices in a country, or
 * `undefined` for `world` and for countries missing from the table.
 */
export function getCurrencyForCountry(countryCode: string): string | undefined {
	return COUNTRY_CURRENCIES[countryCode.toLowerCase()];
}
